package com.echo.http.visibility;

/**
 * 宠物窗口页/窗口详情里<b>逐块可见性的裁剪单位</b>。
 *
 * <p>每个常量对应 {@code RESEARCH-window-content-ownership §4.1} 矩阵的一行（{@code W1}–{@code W15}），
 * 括号里标的就是那一行的编号，便于日后回溯「这一档当初是凭什么定的」。</p>
 *
 * <p>🔴 <b>新增常量默认对所有人不可见。</b>{@link VisibilityMatrix} 是白名单：没在表里显式列出
 * 允许的身份，一律不下发。所以往这个枚举里加一块内容时，<b>忘记配表的后果是「少发了」而不是
 * 「多发了」</b>——这个方向是故意的，理由见 {@link VisibilityMatrix} 类注释。</p>
 */
public enum WindowBlock {

    /** {@code W1} 生命之书。主语是那只它，材料是 owner 自己写的，不含第三方信息与行为度量。 */
    LIFE_BOOK,

    /** {@code W2} 暖光浓度。⚠️ 它今天是可还原精确人数的浮点，见卡点信箱第三条。 */
    WARMTH_LEVEL,

    /**
     * {@code W3} 暖光面孔墙的头像列表。
     *
     * <p>🔴 材料是<b>第三方的身份</b>，不是窗主的数据——窗主无权替名单上的人决定要不要公开。
     * 那些人按下「我记得它」时，产品承诺的是 {@code D8} 静默誓约 + {@code D4} 不显精确数 +
     * {@code CR6} 不出现人数，<b>没有任何一处告诉他头像会挂在窗上给别人看</b>。</p>
     */
    REMEMBER_FACES,

    /**
     * {@code W4} 「我记得没」。
     *
     * <p>🔴 这一块<b>不是这扇窗的数据</b>，是来访者自己的状态。把它当成窗的属性去裁剪是判错了主语，
     * 所以它对三档身份一律可见。</p>
     */
    ME_REMEMBERED,

    /** {@code W5} 「我记得它」按钮。自己的窗不能记得自己，故本人不出。 */
    REMEMBER_BUTTON,

    /** {@code W8} 献花按钮。同 {@code W4}：额度与 bondMark 都是访客自己的数据，不是窗的属性。 */
    FLOWER_BUTTON,

    /** {@code W9} 收花数。{@code D5} 不排名 + owner 私域。 */
    FLOWERS_RECEIVED,

    /** {@code W10} 看过数。{@code D4} 已定「只归 owner 内部」。 */
    SEEN_COUNT,

    /** {@code W11} 明信片<b>已解锁</b>位（图 + caption + 日期）。⚠️ 陌生人一格待决，见卡点信箱第一条。 */
    POSTCARD_UNLOCKED,

    /**
     * {@code W12} 明信片<b>未解锁</b>位 + {@code unlockHint}。
     *
     * <p>🔴 它泄露的不是内容，是<b>主人的行为度量</b>：「相伴满 100 天」「温度到 90°」。
     * 而温度这个更弱的信号已被 {@code B5} 判为陌生人不出——一个会说出温度门槛的提示位，
     * 敏感度不该低于温度本身。故收成仅本人（对 {@code §10.3 B15}「仅亲友」的一处收紧）。</p>
     */
    POSTCARD_LOCKED,

    /** {@code W13} 羁绊温度。 */
    TEMPERATURE,

    /** {@code W14} 可见性设置行（「🔒 当前：仅自己可见 / …」）。主人自己的配置状态，给访客看等于泄露设置。 */
    VISIBILITY_SETTING,

    /**
     * {@code W15} 回访近况<b>列表</b>（AI 生成的近况，≤3 条，{@code §10.3 B11}）。
     *
     * <p>⚠️ 不要和窗口卡上那一行 {@code recent} 混为一谈：那一行是「公开的卡与基本介绍」的一部分，
     * 广场每张卡上都有，随窗的可见性三档走，不在本枚举的裁剪范围内。</p>
     *
     * <h3>🔴 已裁定：亲友动态圈（{@code reels}）继续发给亲友，这<b>不是</b>漏改</h3>
     * <p>{@code GET /relations} 的每条亲友都带 {@code reels} = 对方宠物最新 ≤3 条近况正文
     * （{@code EchoApi.reelsOf}），看起来与本块「仅本人」的档位矛盾。<b>已拍板：不动。</b></p>
     * <p><b>依据</b>：{@code B11} 的约束范围是<b>宠物窗口页</b>，亲友动态圈是另一个面，两者不是
     * 同一处曝光。动态圈是用户主动把对方加为亲友之后的关系内产物，与陌生人在窗口页看到私密层
     * 不是一回事。反过来按「亲友也不该看近况正文」执行，亲友动态圈整个功能没有内容可放，
     * 等于删掉一个已成型的功能（{@code ReelViewer} / {@code hasUnseenReel} / 红点）。</p>
     * <p>🔴 <b>所以：看到同一份 AI 近况正文在两个面上口径不同，不要顺手「修」掉。</b>
     * 要改先推翻这条裁定。</p>
     */
    RECENT_ECHO_LIST
}
